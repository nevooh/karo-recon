// Save or replace the school's Paybill number and Daraja keys. Admin only.
// The keys are stored encrypted and are NEVER shown again. Replacing existing keys needs the
// reset rules (type RESET or the school's name, and your own password).
router.put('/schools/:schoolId/mpesa/keys', requireAdmin, requirePin, async (req, res) => {
  const schoolId = Number(req.params.schoolId);
  const b = req.body || {};
  const input = { paybill: b.paybill, consumerKey: b.consumer_key, consumerSecret: b.consumer_secret };
  validateKeysInput(input);                                    // a typo never costs a password attempt
  const cur = (await pool.query(
    `SELECT (mpesa_consumer_key_enc IS NOT NULL AND mpesa_consumer_secret_enc IS NOT NULL) AS keys_saved FROM schools WHERE id = $1`, [schoolId])).rows[0] || {};
  if (cur.keys_saved) {
    await checkConfirmText({ schoolId, text: b.confirm_text });
    await checkAdminPassword({ schoolId, staffId: req.staff.staffId, password: b.password, ip: req.ip, what: 'mpesa' });
  }
  const { replaced } = await saveMpesaKeys({ schoolId, ...input });
  await ensureSelected(schoolId, 'mpesa');
  await logAudit({ schoolId, staffId: req.staff.staffId, action: replaced ? 'mpesa_keys_replaced' : 'mpesa_keys_saved', ip: req.ip });
  res.json({ ok: true, replaced });
});

