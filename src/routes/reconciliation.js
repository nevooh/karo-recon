// One bank account number belongs to ONE school. Without this check, School B could register
// School A's number, the webhook would see two schools, refuse to guess, and School A's
// payments would be dropped. (The database also enforces it - see fee_structure_schema.sql.)
const ACCOUNT_TAKEN = 'This account number is already registered to another school. If it is really yours, contact Karo Recon support.';
async function accountTakenByAnotherSchool(providerCode, accountNumber, schoolId) {
  const r = await pool.query(
    `SELECT 1 FROM school_bank_connections sbc JOIN bank_providers bp ON bp.id = sbc.provider_id
      WHERE bp.code = $1 AND sbc.account_number = $2 AND sbc.school_id <> $3 LIMIT 1`,
    [providerCode, accountNumber, schoolId]);
  return r.rows.length > 0;
}
const isDuplicateKey = (err) => Boolean(err) && err.code === '23505';   // the database's "already exists"

// Saving a bank connection (for example KCB's account number). Admin only.
// Equity and Co-op are NOT allowed here: their password must be GENERATED by the
// Connect routes below. Replacing an existing connection needs the full reset rules
// (confirm_text + your password + 10-minute wait) - see services/credentialGuard.js.
router.post('/schools/:schoolId/bank-connections', requireAdmin, requirePin, async (req, res) => {
  const { schoolId } = req.params;
  const { provider_code, credentials } = req.body || {};
  let accountNumber = req.body && req.body.account_number;
  if (['equity', 'coop'].includes(provider_code)) {
    return res.status(400).json({ error: 'Use the Connect button for this bank - its password is generated for you' });
  }
  if (provider_code === 'kcb') {
    // Spaces are removed: a number saved with spaces would never match the bank's message.
    accountNumber = String(accountNumber == null ? '' : accountNumber).replace(/\s+/g, '');
    if (!/^[A-Za-z0-9]{4,24}$/.test(accountNumber)) {
      return res.status(400).json({ error: 'Enter the KCB account (or Vooma till) number using letters and numbers only, 4 to 24 characters' });
    }
    if (await accountTakenByAnotherSchool('kcb', accountNumber, Number(schoolId))) return res.status(409).json({ error: ACCOUNT_TAKEN });
  }
  let connection;
  try {
    connection = await changeCredentials(
      { schoolId: Number(schoolId), staffId: req.staff.staffId, bank: provider_code, body: req.body, ip: req.ip },
      () => connectSchoolToBank({
        schoolId: Number(schoolId),
        providerCode: provider_code,
        accountNumber,
        credentials,
      })
    );
  } catch (err) {
    if (isDuplicateKey(err)) return res.status(409).json({ error: ACCOUNT_TAKEN });   // two people registered it at the same instant
    throw err;
  }
  await ensureSelected(Number(schoolId), provider_code);
  res.json(connection);
});

