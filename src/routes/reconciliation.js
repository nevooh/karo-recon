/**
 * Confirm/reject don't have :schoolId in their own URL (just :txnId), so
 * they check the AUTHENTICATED token's schoolId against the transaction's
 * actual school directly. The staff member is whoever the verified token
 * says they are.
 *
 * Safety rules for confirm (all of them exist to stop money being counted
 * twice or put on the wrong student):
 *  - only a payment still waiting for a human (needs_review / unmatched)
 *    can be confirmed. auto_matched payments were ALREADY applied when they
 *    arrived, and confirmed ones were applied when confirmed.
 *  - the transaction row is locked (FOR UPDATE) for the whole operation, so
 *    two staff clicking at the same moment can't both apply it.
 *  - the ledger update runs inside the same database transaction as the
 *    status change: both happen or neither does.
 *  - the chosen student must belong to the same school.
 *  - the payment is applied to the term it arrived in, not whatever term
 *    happens to be current when someone finally clicks confirm.
 */
router.post('/transactions/:txnId/confirm', requireAuth, async (req, res) => {
  const txnId = Number(req.params.txnId);
  const { student_id } = req.body;
  if (!Number.isInteger(txnId)) return res.status(400).json({ error: 'Invalid transaction id' });

  const client = await pool.connect();
  const abort = async (status, error) => {
    await client.query('ROLLBACK');
    return res.status(status).json({ error });
  };

  try {
    await client.query('BEGIN');

    const txnResult = await client.query(`SELECT * FROM transactions WHERE id = $1 FOR UPDATE`, [txnId]);
    const txn = txnResult.rows[0];
    if (!txn) return abort(404, 'Transaction not found');

    if (txn.school_id !== req.staff.schoolId) {
      return abort(403, "This account does not belong to this transaction's school");
    }

    if (!['needs_review', 'unmatched'].includes(txn.match_status)) {
      return abort(409, `This payment is already ${txn.match_status}, so it cannot be confirmed again`);
    }

    const finalStudentId = student_id || txn.matched_student_id;
    if (!finalStudentId) return abort(400, 'No student specified to confirm against');

    const studentResult = await client.query(
      `SELECT id FROM students WHERE id = $1 AND school_id = $2`,
      [finalStudentId, txn.school_id]
    );
    if (studentResult.rows.length === 0) return abort(400, 'That student does not belong to this school');

    let termId = txn.term_id;
    if (!termId) {
      const currentTerm = await getCurrentTerm(txn.school_id, client);
      termId = currentTerm ? currentTerm.id : null;
    }
    // If no term exists at all yet, the payment is still recorded as
    // confirmed, just not applied to a ledger (same as ingest does).
    if (termId) await applyPayment(finalStudentId, termId, txn.amount, client);

    await client.query(
      `UPDATE transactions
       SET match_status = 'confirmed', matched_student_id = $1, confidence = NULL,
           match_reason = 'Manually confirmed by staff', acted_by_staff_id = $3, acted_at = NOW()
       WHERE id = $2`,
      [finalStudentId, txnId, req.staff.staffId]
    );

    await client.query('COMMIT');
    await logAudit({ schoolId: txn.school_id, staffId: req.staff.staffId, action: 'payment_confirmed', ip: req.ip,
      detail: { transaction_id: txnId, student_id: finalStudentId, amount: Number(txn.amount), payer: txn.payer_name || null, source: txn.source || null } });
    res.json({ ok: true });
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
});

/**
 * Reject only works on payments still waiting for a human. An auto_matched
 * or confirmed payment has already been added to a student's balance, and
 * there is no "reverse this payment" feature yet - so rejecting one would
 * leave the ledger and the transaction list disagreeing. Blocked for now.
 */
router.post('/transactions/:txnId/reject', requireAuth, async (req, res) => {
  const txnId = Number(req.params.txnId);
  if (!Number.isInteger(txnId)) return res.status(400).json({ error: 'Invalid transaction id' });

  const updated = await pool.query(
    `UPDATE transactions
     SET match_status = 'rejected', acted_by_staff_id = $1, acted_at = NOW()
     WHERE id = $2 AND school_id = $3 AND match_status IN ('needs_review', 'unmatched')
     RETURNING id, amount, payer_name, source`,
    [req.staff.staffId, txnId, req.staff.schoolId]
  );
  if (updated.rows.length > 0) {
    const t = updated.rows[0];
    await logAudit({ schoolId: req.staff.schoolId, staffId: req.staff.staffId, action: 'payment_rejected', ip: req.ip,
      detail: { transaction_id: txnId, amount: Number(t.amount), payer: t.payer_name || null, source: t.source || null } });
    return res.json({ ok: true });
  }

  // Nothing updated - work out why, so the message is useful.
  const lookup = await pool.query(`SELECT school_id, match_status FROM transactions WHERE id = $1`, [txnId]);
  const txn = lookup.rows[0];
  if (!txn) return res.status(404).json({ error: 'Transaction not found' });
  if (txn.school_id !== req.staff.schoolId) {
    return res.status(403).json({ error: "This account does not belong to this transaction's school" });
  }
  return res.status(409).json({
    error: `This payment is already ${txn.match_status}, so it cannot be rejected. Reversing an applied payment is not supported yet.`,
  });
});

