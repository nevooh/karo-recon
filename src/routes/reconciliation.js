/**
 * Read-only: every payment for the school, newest first, with the student it was
 * matched to. Filters: status, source, q (search), limit, offset.
 */
router.get('/schools/:schoolId/transactions', async (req, res) => {
  const schoolId = Number(req.params.schoolId);
  const limit = Math.min(Math.max(Number(req.query.limit) || 25, 1), 200);
  const offset = Math.max(Number(req.query.offset) || 0, 0);
  const where = ['t.school_id = $1'];
  const params = [schoolId];
  if (req.query.status) { params.push(String(req.query.status)); where.push(`t.match_status = $${params.length}`); }
  if (req.query.source) { params.push(String(req.query.source)); where.push(`t.source = $${params.length}`); }
  if (req.query.q) {
    params.push('%' + String(req.query.q) + '%');
    const n = params.length;
    where.push(`(t.narration ILIKE $${n} OR t.payer_name ILIKE $${n} OR t.external_ref ILIKE $${n} OR t.amount::text ILIKE $${n} OR s.full_name ILIKE $${n} OR s.admission_no ILIKE $${n})`);
  }
  const from = `FROM transactions t LEFT JOIN students s ON s.id = t.matched_student_id WHERE ${where.join(' AND ')}`;
  const count = await pool.query(`SELECT COUNT(*)::int AS n ${from}`, params);
  const rows = await pool.query(
    `SELECT t.*, s.full_name AS student_name, s.admission_no ${from} ORDER BY t.id DESC LIMIT ${limit} OFFSET ${offset}`, params);
  rows.rows.forEach((r) => { delete r.raw_payload; delete r.raw; });
  res.json({ total: count.rows[0].n, rows: rows.rows });
});

/**
 * Read-only: students with their balance for the CURRENT term
 * (balance = brought forward + fees charged - paid). Filters: q, limit, offset.
 */
router.get('/schools/:schoolId/students', async (req, res) => {
  const schoolId = Number(req.params.schoolId);
  const limit = Math.min(Math.max(Number(req.query.limit) || 40, 1), 200);
  const offset = Math.max(Number(req.query.offset) || 0, 0);
  const term = await getCurrentTerm(schoolId);
  const params = [schoolId, term ? term.id : null];
  let search = '';
  if (req.query.q) { params.push('%' + String(req.query.q) + '%'); search = ' AND (s.full_name ILIKE $3 OR s.admission_no ILIKE $3)'; }
  const base = `FROM students s LEFT JOIN student_term_ledger l ON l.student_id = s.id AND l.term_id = $2 WHERE s.school_id = $1${search}`;
  const bal = 'COALESCE(l.opening_balance,0) + COALESCE(l.fees_charged,0) - COALESCE(l.amount_paid,0)';
  const totals = await pool.query(
    `SELECT COUNT(*)::int AS students, COALESCE(SUM(COALESCE(l.opening_balance,0)+COALESCE(l.fees_charged,0)),0) AS charged,
            COALESCE(SUM(l.amount_paid),0) AS paid, COALESCE(SUM(${bal}),0) AS outstanding ${base}`, params);
  const rows = await pool.query(
    `SELECT s.id, s.admission_no, s.full_name, s.status, COALESCE(l.fees_charged,0) AS fees_charged,
            COALESCE(l.amount_paid,0) AS amount_paid, ${bal} AS balance ${base} ORDER BY s.admission_no LIMIT ${limit} OFFSET ${offset}`, params);
  const t = totals.rows[0];
  res.json({
    term: term ? { id: term.id } : null,
    totals: { students: t.students, charged: Number(t.charged), paid: Number(t.paid), outstanding: Number(t.outstanding) },
    rows: rows.rows.map((r) => ({ ...r, fees_charged: Number(r.fees_charged), amount_paid: Number(r.amount_paid), balance: Number(r.balance) })),
  });
});

/**
 * The four payment channels for this school: picked or not, the identifier messages
 * are matched on, whether a notification login is set, recent activity, and a status
 * (setup_needed / waiting_for_bank / connected). NEVER returns keys, passwords or fingerprints.
 */
async function channelList(schoolId) {
  const school = (await pool.query('SELECT mpesa_shortcode FROM schools WHERE id = $1', [schoolId])).rows[0] || {};
  const conns = await pool.query(
    `SELECT bp.code, sbc.account_number, sbc.credentials_enc FROM school_bank_connections sbc
     JOIN bank_providers bp ON bp.id = sbc.provider_id WHERE sbc.school_id = $1`, [schoolId]);
  const activity = await pool.query(
    `SELECT source, COUNT(*)::int AS payments, MAX(received_at) AS last_payment_at FROM transactions WHERE school_id = $1 GROUP BY source`, [schoolId]);
  const picked = await getSelected(schoolId);
  const act = {};
  activity.rows.forEach((r) => { act[r.source] = r; });
  const byCode = {};
  conns.rows.forEach((r) => { byCode[r.code] = r; });
  const loginSet = (c) => {
    if (!c) return null;
    try { const x = JSON.parse(decrypt(c.credentials_enc) || '{}'); return Boolean(x.ins_password_hash || x.ipn_password_hash || x.ipn_password); } catch (e) { return false; }
  };
  const row = (channel, label, how, identifierLabel, identifier, setUp, login) => {
    const payments = act[channel] ? act[channel].payments : 0;
    return {
      channel, label, how, identifier_label: identifierLabel, identifier: identifier || null,
      connected: setUp, login_set: login,
      selected: picked.includes(channel), status: statusFor(setUp, payments),
      payments, last_payment_at: act[channel] ? act[channel].last_payment_at : null,
    };
  };
  // KCB also tells the screen if OUR side is ready (is KCB's key installed?) and the address for the request letter.
  const publicBase = (process.env.PUBLIC_BASE_URL || '').replace(/\/+$/, '');
  const kcbRow = row('kcb', 'KCB', 'Instant notification, signed by KCB', 'Account or till', byCode.kcb && byCode.kcb.account_number, Boolean(byCode.kcb), null);
  Object.assign(kcbRow, {
    key_status: kcbKeyStatus(),                                   // 'ok' | 'missing' | 'invalid' (never the key itself)
    unsigned_allowed: process.env.NODE_ENV !== 'production',      // outside production, a missing key is only a warning
    callback_url: (publicBase || 'https://YOUR-DOMAIN') + '/webhooks/kcb/ipn',
    callback_url_is_placeholder: !publicBase,
  });
  // M-Pesa is only "set up" once our two addresses are registered with Safaricom (or payments already arrive).
  const mpesaDetails = await mpesaStatus(schoolId, Boolean(act.mpesa && act.mpesa.payments > 0));
  const mpesaRow = row('mpesa', 'M-Pesa Paybill', 'Instant notification from Safaricom', 'Paybill number', school.mpesa_shortcode, mpesaDetails.stage === 'registered', null);
  Object.assign(mpesaRow, { mpesa: mpesaDetails });
  return [
    mpesaRow,
    kcbRow,
    row('equity', 'Equity', 'Instant notification (payments and account alerts)', 'Callback username', byCode.equity && byCode.equity.account_number, Boolean(byCode.equity), loginSet(byCode.equity)),
    row('coop', 'Co-op Bank', 'Instant notification (INS)', 'Account number', byCode.coop && byCode.coop.account_number, Boolean(byCode.coop), loginSet(byCode.coop)),
  ];
}

