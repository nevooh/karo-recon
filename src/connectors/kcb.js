/**
 * KCB Buni IPN connector - written from KCB's own specification documents:
 *   IPN-Account         money credited to a KCB bank account         (flat payload)
 *   Bill-Notification   over-the-counter and agent deposits          (flat payload, same fields)
 *   IPN-Till  v1.0.4    payments to a KCB Till / Vooma               (NESTED payload)
 *
 * KCB pushes a notification the moment money is credited, so only credits
 * ever arrive (no salaries or charges going out). The two shapes are told
 * apart by looking for "requestPayload", which only the Till shape has.
 *
 * KCB signs every notification (SHA256withRSA, header "signature") and the
 * spec says checking it is REQUIRED - it is tested during KCB's UAT. Without
 * the check anyone could post a fake payment to our URL.
 */
const crypto = require('crypto');

const isTillFormat = (body) => Boolean(body && body.requestPayload);
const cleanAmount = (value) => Number(String(value == null ? '' : value).replace(/,/g, ''));

function tillNotification(body) {
  const additional = (body.requestPayload && body.requestPayload.additionalData) || {};
  return additional.notificationData || {};
}

/** Turns either KCB shape into what ingestPayment() expects. */
function normalizeIPNPayload(body) {
  if (isTillFormat(body)) {
    const n = tillNotification(body);
    return {
      source: 'kcb',
      external_ref: n.transactionID,
      amount: cleanAmount(n.transactionAmt),
      payer_phone: n.debitMSISDN,
      payer_name: [n.firstName, n.middleName, n.lastName].filter(Boolean).join(' '),
      narration: n.businessKey || n.narration, // businessKey = the bill reference the payer typed
      raw: body,
    };
  }
  return {
    source: 'kcb',
    external_ref: body.transactionReference,
    amount: cleanAmount(body.transactionAmount),
    payer_phone: body.customerMobileNumber,
    payer_name: body.customerName,
    narration: body.customerReference || body.narration,
    raw: body,
  };
}

/**
 * Identifiers that could tell us which school was paid, most specific first.
 * KCB's documents don't say which one carries the school's own number, so we
 * offer all of them and the route picks the first that matches exactly one
 * school. (A real UAT notification will show which one it is.)
 */
function extractOrgIdentifiers(body) {
  const raw = isTillFormat(body)
    ? [body.requestPayload.primaryData && body.requestPayload.primaryData.businessKey]
    : [body.creditAccountIdentifier, body.tillNumber, body.organizationShortCode];
  return raw.filter(Boolean).map(String);
}

/**
 * The acknowledgement KCB expects, in the same shape it used.
 * transactionID is OUR id for the payment (the Till spec says "generated by
 * your system"), statusCode "0" means success.
 */
function buildAckResponse(body, ourTransactionId) {
  if (isTillFormat(body)) {
    const header = body.header || {};
    return {
      header: {
        messageID: header.messageID || '',
        originatorConversationID: header.originatorConversationID || '',
        statusCode: '0',
        statusMessage: 'Notification received',
      },
      responsePayload: { transactionInfo: { transactionId: String(ourTransactionId) } },
    };
  }
  return { transactionID: String(ourTransactionId), statusCode: '0', statusMessage: 'Notification received' };
}

/* ---------------- signature check ---------------- */

// KCB gives you its public key; paste it in .env as KCB_IPN_PUBLIC_KEY
// (a PEM block with \n for new lines, or just the base64 text).
function loadPublicKey() {
  let key = process.env.KCB_IPN_PUBLIC_KEY;
  if (!key) return null;
  key = key.replace(/\\n/g, '\n').trim();
  if (!key.includes('BEGIN')) {
    key = '-----BEGIN PUBLIC KEY-----\n' + key.replace(/\s+/g, '').match(/.{1,64}/g).join('\n') + '\n-----END PUBLIC KEY-----';
  }
  return key;
}

// Is OUR side ready? 'ok' = a readable key is installed, 'missing' = none set, 'invalid' = set but unreadable.
// (Only this word leaves the server, never the key.)
function keyStatus() {
  const pem = loadPublicKey();
  if (!pem) return 'missing';
  try { crypto.createPublicKey(pem); return 'ok'; } catch (err) { return 'invalid'; }
}

function verifySignature(rawBody, signature, publicKey) {
  if (!rawBody || !signature || !publicKey) return false;
  try {
    const verifier = crypto.createVerify('RSA-SHA256');
    verifier.update(rawBody);
    verifier.end();
    return verifier.verify(publicKey, String(signature).trim(), 'base64');
  } catch (err) {
    return false;
  }
}

/**
 * { ok: true }                 signature is genuine
 * { ok: true, skipped: true }  no key set AND not production (local testing only)
 * { ok: false, reason }        refuse the notification
 * In production, a missing key means REFUSE - never accept unsigned payments.
 */
function checkSignature(req) {
  const publicKey = loadPublicKey();
  if (!publicKey) {
    if (process.env.NODE_ENV === 'production') {
      return { ok: false, reason: 'KCB_IPN_PUBLIC_KEY is not set - refusing unsigned notifications in production' };
    }
    return { ok: true, skipped: true };
  }
  return verifySignature(req.rawBody, req.get('signature'), publicKey)
    ? { ok: true }
    : { ok: false, reason: 'signature missing or does not match the body' };
}

module.exports = { normalizeIPNPayload, extractOrgIdentifiers, buildAckResponse, checkSignature, verifySignature, keyStatus };